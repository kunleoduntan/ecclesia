import io, base64, json
from datetime import datetime
import frappe
from frappe.utils import nowdate, now_datetime, flt

try:
    import openpyxl
    from openpyxl.styles import (
        PatternFill, Font, Alignment, Border, Side,
        GradientFill
    )
    from openpyxl.utils import get_column_letter
    from openpyxl.chart import BarChart, Reference
    from openpyxl.chart.series import SeriesLabel
    HAS_OPENPYXL = True
except ImportError:
    HAS_OPENPYXL = False

# ── BRAND COLOURS ─────────────────────────────────────────────────────────
NAVY      = "1E2D5A"
PURPLE    = "5B2D8E"
TEAL      = "0D9488"
AMBER     = "B45309"
GREEN     = "059669"
RED       = "DC2626"
WHITE     = "FFFFFF"
LGREY     = "F1F5F9"
MGREY     = "E5E7EB"
DGREY     = "374151"
GOLD      = "F59E0B"

def _fill(hex_color):
    return PatternFill("solid", fgColor=hex_color)

def _font(hex_color=DGREY, bold=False, size=10, italic=False):
    return Font(color=hex_color, bold=bold, size=size,
                italic=italic, name="Calibri")

def _align(h="left", v="center", wrap=False):
    return Alignment(horizontal=h, vertical=v, wrap_text=wrap)

def _border(color=MGREY, style="thin"):
    s = Side(border_style=style, color=color)
    return Border(left=s, right=s, top=s, bottom=s)

def _bottom_border(color=MGREY):
    b = Side(border_style="thin", color=color)
    return Border(bottom=b)


class EcclesiaReport:
    """
    Wrapper that builds a beautiful multi-sheet Excel workbook.

    Usage:
        wb = EcclesiaReport("Cycle Completion", filters, columns, data)
        wb.add_summary_sheet(summary_rows)
        wb.add_chart("bar", ...)
        return wb.to_base64()
    """

    def __init__(self, report_title, filters, columns, data,
                 subtitle=None, company=None):
        if not HAS_OPENPYXL:
            frappe.throw("openpyxl is required. Run: pip install openpyxl --break-system-packages")

        self.wb     = openpyxl.Workbook()
        self.title  = report_title
        self.filters = filters or {}
        self.columns = columns
        self.data    = data
        self.subtitle = subtitle or ""
        self.company  = company or frappe.defaults.get_global_default("company") or "Company"
        self.ws_data  = None

        self._build_cover_sheet()
        self._build_data_sheet()

    # ── COVER SHEET ───────────────────────────────────────────────────────

    def _build_cover_sheet(self):
        ws = self.wb.active
        ws.title = "Cover"
        ws.sheet_view.showGridLines = False
        ws.column_dimensions["A"].width = 4
        ws.column_dimensions["B"].width = 28
        ws.column_dimensions["C"].width = 42
        ws.column_dimensions["D"].width = 20

        # Company header banner (rows 1-6)
        for r in range(1, 7):
            for c in range(1, 10):
                cell = ws.cell(row=r, column=c)
                cell.fill = _fill(NAVY)

        # Company name
        ws.merge_cells("B2:D3")
        c = ws["B2"]
        c.value = self.company.upper()
        c.font  = _font(WHITE, bold=True, size=16)
        c.alignment = _align("left", "bottom")
        c.fill  = _fill(NAVY)

        ws.merge_cells("B4:D4")
        c = ws["B4"]
        c.value = "Ecclesia HR Platform · Value Impacts Consulting"
        c.font  = _font("A0AEC0", size=9)
        c.alignment = _align()
        c.fill  = _fill(NAVY)

        # Purple accent bar
        for c_idx in range(1, 10):
            cell = ws.cell(row=6, column=c_idx)
            cell.fill = _fill(PURPLE)

        # Report title block (rows 8-12)
        ws.merge_cells("B8:D9")
        t = ws["B8"]
        t.value = self.title
        t.font  = _font(NAVY, bold=True, size=18)
        t.alignment = _align("left", "center")

        if self.subtitle:
            ws.merge_cells("B10:D10")
            s = ws["B10"]
            s.value = self.subtitle
            s.font  = _font(PURPLE, size=11)
            s.alignment = _align()

        # Metadata table (rows 12+)
        meta = [
            ("Generated On",  frappe.format_date(nowdate()) + "  " + now_datetime().strftime("%H:%M")),
            ("Generated By",  frappe.session.user),
            ("Total Records", str(len(self.data))),
        ]
        for k, v in self.filters.items():
            if v:
                meta.append((k.replace("_", " ").title(), str(v)))

        row = 13
        ws.row_dimensions[12].height = 10
        for label, value in meta:
            ws.row_dimensions[row].height = 20
            lc = ws.cell(row=row, column=2, value=label)
            lc.font      = _font(DGREY, bold=True, size=10)
            lc.alignment = _align()
            lc.fill      = _fill(LGREY)
            lc.border    = _bottom_border()

            vc = ws.cell(row=row, column=3, value=value)
            vc.font      = _font(NAVY, size=10)
            vc.alignment = _align()
            vc.border    = _bottom_border()
            row += 1

        # Confidential watermark
        ws.merge_cells(f"B{row+2}:D{row+2}")
        c2 = ws[f"B{row+2}"]
        c2.value     = "CONFIDENTIAL — For Authorised Personnel Only"
        c2.font      = _font(RED, bold=True, size=9, italic=True)
        c2.alignment = _align("center")

    # ── DATA SHEET ────────────────────────────────────────────────────────

    def _build_data_sheet(self):
        ws = self.wb.create_sheet(title="Data")
        ws.sheet_view.showGridLines = False
        self.ws_data = ws

        # === Report title row ===
        ws.row_dimensions[1].height = 14
        ws.row_dimensions[2].height = 32
        ws.merge_cells(f"A2:{get_column_letter(len(self.columns))}2")
        tc = ws["A2"]
        tc.value     = self.title
        tc.font      = _font(WHITE, bold=True, size=13)
        tc.fill      = _fill(NAVY)
        tc.alignment = _align("center", "center")

        # === Column headers (row 3) ===
        ws.row_dimensions[3].height = 22
        for ci, col in enumerate(self.columns, 1):
            lbl  = col.get("label", col.get("fieldname", ""))
            cell = ws.cell(row=3, column=ci, value=lbl)
            cell.font      = _font(WHITE, bold=True, size=10)
            cell.fill      = _fill(PURPLE)
            cell.alignment = _align("center", "center")
            cell.border    = _border(NAVY, "medium")
            # Column width
            w = col.get("width", 120) / 7
            w = max(10, min(40, w))
            ws.column_dimensions[get_column_letter(ci)].width = w

        # === Data rows ===
        totals = {}
        for ri, row_data in enumerate(self.data, 4):
            ws.row_dimensions[ri].height = 16
            shade = LGREY if ri % 2 == 0 else WHITE
            for ci, col in enumerate(self.columns, 1):
                fname = col.get("fieldname", "")
                if isinstance(row_data, dict):
                    val = row_data.get(fname)
                else:
                    val = getattr(row_data, fname, None)

                cell = ws.cell(row=ri, column=ci, value=val)
                cell.fill      = _fill(shade)
                cell.border    = _bottom_border()
                cell.alignment = _align("center" if col.get("fieldtype") in
                    ("Int", "Float", "Percent", "Currency") else "left")

                # Format numbers
                ft = col.get("fieldtype", "")
                if ft in ("Float", "Percent") and val is not None:
                    cell.number_format = "0.0%25" if ft == "Percent" else "0.00"
                elif ft == "Currency" and val is not None:
                    cell.number_format = '\u20a6#,##0.00'
                elif ft == "Int" and val is not None:
                    cell.number_format = "#,##0"

                # Colour coding for known status fields
                if fname in ("status", "goal_set", "self_appraisal",
                             "manager_review", "emails_sent"):
                    sval = str(val or "")
                    if any(x in sval for x in ("Done", "✅", "Shortlisted", "Yes", "Passed")):
                        cell.font = _font(GREEN, bold=True)
                    elif any(x in sval for x in ("Pending", "⏳", "No", "Rejected")):
                        cell.font = _font(AMBER, bold=True)
                    elif any(x in sval for x in ("Failed", "🔴", "Overdue")):
                        cell.font = _font(RED, bold=True)

                # Accumulate totals for numeric cols
                if ft in ("Int", "Float", "Percent") and val is not None:
                    totals[ci] = totals.get(ci, 0) + flt(val)

        # === Totals row ===
        if totals and len(self.data) > 1:
            tr = len(self.data) + 4
            ws.row_dimensions[tr].height = 20
            tc = ws.cell(row=tr, column=1, value="TOTAL / AVERAGE")
            tc.font      = _font(WHITE, bold=True, size=10)
            tc.fill      = _fill(NAVY)
            tc.border    = _border(NAVY, "medium")
            tc.alignment = _align("center", "center")
            for ci, col in enumerate(self.columns, 1):
                cell = ws.cell(row=tr, column=ci)
                cell.fill   = _fill(NAVY)
                cell.border = _border(NAVY, "medium")
                if ci in totals and ci > 1:
                    ft = col.get("fieldtype", "")
                    val = totals[ci] / len(self.data) if ft == "Percent" else totals[ci]
                    cell.value     = round(val, 1)
                    cell.font      = _font(GOLD, bold=True, size=10)
                    cell.alignment = _align("center", "center")

        # Freeze header
        ws.freeze_panes = "A4"

        # Auto-filter
        ws.auto_filter.ref = (
            f"A3:{get_column_letter(len(self.columns))}{len(self.data)+3}")

    # ── BAR CHART ─────────────────────────────────────────────────────────

    def add_bar_chart(self, title, cat_col_idx, val_col_idxes,
                      sheet_title="Chart", legend_titles=None):
        """Add a bar chart sheet."""
        ws_chart = self.wb.create_sheet(title=sheet_title)
        data_rows = len(self.data)
        if data_rows < 1:
            return

        chart = BarChart()
        chart.type  = "col"
        chart.grouping = "clustered"
        chart.title = title
        chart.style = 10
        chart.height = 14
        chart.width  = 22

        # Category axis (column labels)
        cats = Reference(self.ws_data,
                         min_col=cat_col_idx, min_row=4,
                         max_row=data_rows + 3)

        for i, vcol in enumerate(val_col_idxes):
            data_ref = Reference(self.ws_data,
                                 min_col=vcol, min_row=3,
                                 max_row=data_rows + 3)
            ser = openpyxl.chart.Series(data_ref, title_from_data=True)
            if legend_titles and i < len(legend_titles):
                ser.title = SeriesLabel(v=legend_titles[i])
            chart.series.append(ser)

        chart.set_categories(cats)
        chart.shape = 4
        ws_chart.add_chart(chart, "B2")
        ws_chart.sheet_view.showGridLines = False

    # ── RETURN ────────────────────────────────────────────────────────────

    def to_base64(self):
        """Save workbook to bytes and return base64 string."""
        output = io.BytesIO()
        self.wb.save(output)
        output.seek(0)
        return base64.b64encode(output.read()).decode()

    def to_response(self, filename=None):
        """Return {filename, filecontent (b64), type} dict for JS download."""
        ts  = now_datetime().strftime("%Y%m%d_%H%M")
        fname = filename or f"{self.title.replace(' ','_')}_{ts}.xlsx"
        return {
            "filename":    fname,
            "filecontent": self.to_base64(),
            "type":        "xlsx",
        }
