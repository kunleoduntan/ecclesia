"""
Audit Checklist Template — Controller
======================================
Manages reusable IIA/COSO-aligned checklist templates.
Auto-generated by checklist_generator on DocType registration;
auditors can also build and customise their own templates.

On save:
  ▸ Renumbers all items sequentially
  ▸ Validates that every item has a Test Procedure
  ▸ Pulls classification from registry if blank
  ▸ Enforces only one 'is_default = 1' per DocType
"""

import frappe
from frappe.model.document import Document


class AuditChecklistTemplate(Document):

    # ──────────────────────────────────────────────────────────────────────
    # Lifecycle hooks
    # ──────────────────────────────────────────────────────────────────────

    def before_save(self):
        self._pull_classification_from_registry()

    def validate(self):
        self._renumber_items()
        self._validate_items()

    def on_update(self):
        """Ensure only one default template exists per DocType."""
        if self.is_default and self.doctype_name:
            frappe.db.sql(
                """
                UPDATE `tabAudit Checklist Template`
                SET    is_default = 0
                WHERE  doctype_name = %s
                  AND  name        != %s
                  AND  is_default  = 1
                """,
                (self.doctype_name, self.name),
            )

    # ──────────────────────────────────────────────────────────────────────
    # Helpers
    # ──────────────────────────────────────────────────────────────────────

    def _pull_classification_from_registry(self):
        if self.doctype_name and not self.classification:
            cls = frappe.db.get_value(
                "Auditable DocType Registry",
                {"doctype_name": self.doctype_name},
                "doctype_classification",
            )
            if cls:
                self.classification = cls

    def _renumber_items(self):
        for idx, item in enumerate(self.checklist_items or [], start=1):
            item.item_number = idx

    def _validate_items(self):
        for item in self.checklist_items or []:
            if not (item.test_procedure or "").strip():
                frappe.throw(
                    f"Checklist item #{item.item_number} "
                    f"({item.control_area or 'unknown area'}): "
                    "Test Procedure is required."
                )